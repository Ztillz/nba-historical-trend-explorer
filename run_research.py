"""Build the website research data, first-20-game findings, and evidence CSV."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from src.research.core import (
    BOOTSTRAP_REPS, CHECKPOINTS, FEATURES, HORIZONS, SEED, TARGETS,
    benchmark, build_features, correlations, load_snapshot,
)

ROOT = Path(__file__).resolve().parent


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n", encoding="utf-8")


def generate(data_directory: Path, reps=BOOTSTRAP_REPS):
    rows, coverage = build_features(load_snapshot(data_directory))
    columns = list(rows[0]) if rows else []
    write_json(data_directory / "research.json", {
        "schema_version": 1, "checkpoints": CHECKPOINTS, "horizons": HORIZONS,
        "features": [{"id": key, "label": label} for key, (_, label) in FEATURES.items()],
        "targets": TARGETS, "columns": columns, "rows": [[row[key] for key in columns] for row in rows],
        "coverage": coverage, "seed": SEED, "bootstrap_reps": reps,
        "source": "Checked-in team_games.json; regular-season box-score differentials",
    })
    default = [row for row in rows if row["checkpoint"] == 20 and row["horizon"] == "remaining"]
    split = "2016-17"
    report = dict(checkpoint=20, horizon="remaining", target="future_win_pct", holdout_start=split,
                  seed=SEED, bootstrap_reps=reps, sample_size=len(default),
                  correlations=correlations(default, "future_win_pct", split, reps),
                  benchmark=benchmark(default, "future_win_pct", split, ["rebound_diff", "assist_diff", "turnover_diff"]))
    write_json(data_directory / "first20_report.json", report)
    csv_path = ROOT / "research" / "first20_evidence.csv"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        writer.writerows(default)
    md = ["# First 20 games → remaining-season performance", "",
          "Generated by `python run_research.py` from the checked-in snapshot. See [methods](METHODS.md).", "",
          f"{len(default):,} team-seasons. Observation: games 1–20. Target: win percentage from game 21 onward.",
          f"Earlier seasons: before {split}; later evaluation: {split} onward. Seed {SEED}; {reps} whole-season bootstrap resamples.", "",
          "## Exploratory associations", "", "| Early statistic | n | Spearman ρ | 95% season-bootstrap interval | Earlier ρ | Later ρ |",
          "|---|---:|---:|---|---:|---:|"]
    fmt = lambda value: "unavailable" if value is None else f"{value:.3f}"
    for item in report["correlations"]:
        ci = item["interval"]
        interval = "unavailable" if ci is None else f"[{ci[0]:.3f}, {ci[1]:.3f}]"
        md.append(f"| {item['label']} | {item['n']} | {fmt(item['rho'])} | {interval} | {fmt(item['earlier_rho'])} | {fmt(item['later_rho'])} |")
    model = report["benchmark"]
    md += ["", "## Fixed chronological benchmark", "", "Extra signals: mean rebound, assist, and turnover differentials.",
           f"All models share {model['earlier_n']} earlier training rows and {model['later_n']} later evaluation rows.", "",
           "| Model | Later MAE (percentage points) | Later RMSE (percentage points) | Later prediction ρ |",
           "|---|---:|---:|---:|"]
    if model["available"]:
        for item in model["models"]:
            md.append(f"| {item['name']} | {100*item['mae']:.3f} | {100*item['rmse']:.3f} | {fmt(item['rho'])} |")
        delta = model["mae_improvement"] * 100
        md += ["", f"Adding the three signals changes MAE by **{delta:+.3f} percentage points of improvement** (positive means lower error)."]
    md += ["", "## Interpretation", "",
           "Correlation screens relationships; the later-season benchmark asks whether the extra signals improve a simple linear baseline. "
           "A strong raw correlation does not establish incremental usefulness. Later seasons have already been inspected during this project, "
           "so this split is a retrospective evaluation, not an untouched prospective test.", "",
           "Intervals resample entire seasons, preserving within-season dependence; repeated franchises across seasons remain a limitation. "
           "No multiple-testing-adjusted significance claims are made. Point differential is points per game, not possession-adjusted net rating.", "",
           "[Evidence CSV](first20_evidence.csv) · [Machine-readable report](../docs/data/first20_report.json) · "
           "[Interactive explorer](https://ztillz.github.io/nba-historical-trend-explorer/research.html)", ""]
    (ROOT / "research" / "FIRST20_FINDINGS.md").write_text("\n".join(md), encoding="utf-8")
    print(f"Built {len(rows):,} feature rows; report and CSV: research/; website data: {data_directory}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-directory", type=Path, default=ROOT / "docs" / "data")
    parser.add_argument("--bootstrap-reps", type=int, default=BOOTSTRAP_REPS)
    args = parser.parse_args()
    if not 100 <= args.bootstrap_reps <= 10000:
        parser.error("--bootstrap-reps must be between 100 and 10000")
    generate(args.data_directory, args.bootstrap_reps)
